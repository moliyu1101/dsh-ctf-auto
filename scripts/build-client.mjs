import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = name => fs.readFileSync(path.join(root, 'client', name), 'utf8').trimEnd();
const css = ['content.css', 'styles.css'].map(read).join('\n');
const source = '// Generated by npm run build:client. Edit client/ sources.\n' +
  [read('runtime.js'), 'var CSS = ' + JSON.stringify(css) + ';', ...['components.js', 'workbench.js', 'platform.js', 'panel.js', 'entry.js'].map(read)].join('\n\n') + '\n';
const target = path.join(root, 'lib/client.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== source) { console.error('Client bundle is stale: run npm run build:client'); process.exitCode = 1; }
} else fs.writeFileSync(target, source);
